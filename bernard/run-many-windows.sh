#!/usr/bin/env bash
# =================================================================================================
# run-many.sh - run BERNARD over several datasets, one after the other, from one command
#
#     bash bernard/run-many.sh  study-a.txt  study-b.txt  study-c.txt
#
# BERNARD analyses ONE settings file per run, and a settings file describes ONE collection of
# data: where it is, what its columns mean, which methods to run. Two datasets that need different
# column names, or different methods, therefore need two settings files - and, until now, two
# commands typed one after the other, each waited for.
#
# This script is that waiting, done for you. Give it the settings files, in the order they should
# run, and it runs them one at a time, unattended, and prints a summary at the end saying which
# ones succeeded, which failed and how long each took.
#
# The shell expands wildcards, so a whole folder of settings files is:
#
#     bash bernard/run-many.sh bernard/cfg/*.txt
#
# and a list of the datasets kept in a file of its own is:
#
#     bash bernard/run-many.sh --list my-runs.txt
#
# where my-runs.txt holds one settings file per line, blank lines and lines beginning with # are
# ignored, and a name written without a folder is looked for next to the list file:
#
#     bernard_cfg_curated.txt      # the curated collection
#     bernard_cfg_controls.txt     # the positive and negative controls
#     #bernard_cfg_HGMA.txt        a # leaves this one out of tonight's queue
#
# -------------------------------------------------------------------------------------------------
# WHAT IT DOES BEFORE IT STARTS
# -------------------------------------------------------------------------------------------------
#
# A full BERNARD run takes minutes to hours, so an overnight queue of six of them that stops on the
# fourth because of a misspelled column name has wasted the night. This script therefore runs
#
#     python3 BERNARD.py --check <settings file>
#
# on EVERY settings file first. That reads the settings and the data, changes nothing, and reports
# everything wrong with either. Only when all of them pass does the first real run start. Use
# --no-check to skip this (for example when the data is generated by an earlier run in the queue).
#
# -------------------------------------------------------------------------------------------------
# WHAT HAPPENS WHEN ONE OF THEM FAILS
# -------------------------------------------------------------------------------------------------
#
# By default the queue carries on with the next dataset, in the same spirit as a single BERNARD run
# carrying on when one correction method fails: one bad dataset should not throw away the results of
# all the others. The failure is reported in the summary at the end, and the exit code is the number
# of runs that failed. Use --stop-on-error to stop at the first failure instead.
#
# -------------------------------------------------------------------------------------------------
# OPTIONS
# -------------------------------------------------------------------------------------------------
#
#     --no-check         do not run --check on the settings files first
#     --stop-on-error    stop the queue at the first run that fails
#     --check-only       run only the checks and calculate nothing (a dry run of the whole queue)
#     --list <file>      read the settings files from <file>, one per line (see below)
#     --log-dir <dir>    also write the full output of each run to <dir>/<settings file name>.log
#     --help
#
# Each settings file is run with the folder it sits in as the work folder, which is what BERNARD
# does when no work folder is given. A settings file whose bernard_input is written relative to
# somewhere else should use an absolute path (/home/anna/study) or a path from the home folder
# (~/study).
#
# Each settings file must point at its OWN bernard_input folder: outputs is wiped at the start of
# every run, so two runs sharing one input folder would leave only the results of the second.
# =================================================================================================

set -u

# Where BERNARD.py sits: next to this script, in src/. Working it out from the script's own
# location means the script may be called from any folder.
script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
bernard_py="${script_dir}/src-windows/BERNARD.py"

python_cmd="${PYTHON:-python3}"

usage() {
    sed -n '3,70p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

# --list: read the settings files from a plain text file, one per line. Empty lines and lines
# beginning with # are ignored, so the list can be commented and a dataset can be left out for one
# night by putting a # in front of it, exactly as a correction method is left out of a run.
# A name written without a folder is looked for next to the list file itself, which is where the
# settings files usually sit, so the list works from whichever folder the script is called in.
read_list() {
    local list_file="$1"
    local list_dir line

    if [ -z "${list_file}" ] || [ ! -f "${list_file}" ]; then
        echo "Error: --list needs a file holding one settings file per line; '${list_file}' is not one."
        exit 1
    fi

    list_dir="$(cd "$(dirname "${list_file}")" && pwd)"

    while IFS= read -r line || [ -n "${line}" ]; do
        line="${line%%#*}"                      # drop a comment at the end of the line
        line="$(echo "${line}" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')"
        [ -z "${line}" ] && continue

        case "${line}" in
            /*|~*) cfg_files+=("${line}") ;;     # an absolute path is taken as it is
            *)     if [ -f "${line}" ]; then     # otherwise: from here if it is here,
                       cfg_files+=("${line}")
                   else                          # and next to the list file if it is not
                       cfg_files+=("${list_dir}/${line}")
                   fi ;;
        esac
    done < "${list_file}"
}

# ---------------------
# Read the command line
# ---------------------
run_checks=yes
check_only=no
stop_on_error=no
log_dir=""
cfg_files=()

while [ $# -gt 0 ]; do
    case "$1" in
        --help|-h)          usage; exit 0 ;;
        --no-check)         run_checks=no; shift ;;
        --check-only)       check_only=yes; shift ;;
        --stop-on-error)    stop_on_error=yes; shift ;;
        --log-dir)          log_dir="${2:-}"; shift 2 ;;
        --list)             read_list "${2:-}"; shift 2 ;;
        -*)                 echo "Unknown option: $1"; echo; usage; exit 1 ;;
        *)                  cfg_files+=("$1"); shift ;;
    esac
done

if [ "${#cfg_files[@]}" -eq 0 ]; then
    echo
    echo "Error: no settings files were given."
    echo
    usage
    exit 1
fi

if [ ! -f "${bernard_py}" ]; then
    echo "Error: BERNARD.py was not found at ${bernard_py}"
    exit 1
fi

# Every settings file must exist before anything starts. A typo in a file name is the cheapest
# possible failure to find, so it is found first.
missing=no
for cfg in "${cfg_files[@]}"; do
    if [ ! -f "${cfg}" ]; then
        echo "Error: the settings file '${cfg}' does not exist."
        missing=yes
    fi
done
[ "${missing}" = yes ] && exit 1

if [ -n "${log_dir}" ]; then
    mkdir -p "${log_dir}" || exit 1
fi

total="${#cfg_files[@]}"

echo
echo "==================================================================================="
echo "BERNARD queue: ${total} settings file(s)"
echo "==================================================================================="
for cfg in "${cfg_files[@]}"; do
    echo "    ${cfg}"
done
echo

# -------------------------------------------------------------------------------------------------
# STAGE 1: check every settings file and the data it points at, before calculating anything.
# -------------------------------------------------------------------------------------------------
if [ "${run_checks}" = yes ]; then
    echo "-----------------------------------------------------------------------------------"
    echo "Checking all settings files and their data (nothing is calculated yet)"
    echo "-----------------------------------------------------------------------------------"
    echo

    failed_checks=0
    for cfg in "${cfg_files[@]}"; do
        echo ">>> --check ${cfg}"
        if ! "${python_cmd}" "${bernard_py}" --check "${cfg}"; then
            failed_checks=$((failed_checks + 1))
        fi
        echo
    done

    if [ "${failed_checks}" -gt 0 ]; then
        echo "==================================================================================="
        echo "${failed_checks} of ${total} settings file(s) did not pass the check."
        echo "Nothing was calculated. Correct them and run this script again,"
        echo "or use --no-check to run anyway."
        echo "==================================================================================="
        exit "${failed_checks}"
    fi

    echo "All ${total} settings file(s) passed."
    echo
fi

if [ "${check_only}" = yes ]; then
    echo "--check-only was given, so nothing was calculated."
    exit 0
fi

# -------------------------------------------------------------------------------------------------
# STAGE 2: run them, one after the other.
# -------------------------------------------------------------------------------------------------
statuses=()
durations=()
queue_started=$(date +%s)

index=0
for cfg in "${cfg_files[@]}"; do
    index=$((index + 1))
    started=$(date +%s)

    echo "==================================================================================="
    echo "[${index}/${total}] ${cfg}"
    echo "started $(date '+%Y-%m-%d %H:%M:%S')"
    echo "==================================================================================="
    echo

    if [ -n "${log_dir}" ]; then
        # tee writes the output to the terminal AND to a file. PIPESTATUS[0] is the exit code of
        # BERNARD itself rather than of tee, which always succeeds.
        "${python_cmd}" "${bernard_py}" "${cfg}" 2>&1 \
            | tee "${log_dir}/$(basename "${cfg}" .txt).log"
        status="${PIPESTATUS[0]}"
    else
        "${python_cmd}" "${bernard_py}" "${cfg}"
        status=$?
    fi

    finished=$(date +%s)
    elapsed=$((finished - started))

    statuses+=("${status}")
    durations+=("${elapsed}")

    echo
    if [ "${status}" -eq 0 ]; then
        printf 'FINISHED  %s  (%dh %02dm %02ds)\n' \
               "${cfg}" $((elapsed / 3600)) $(((elapsed % 3600) / 60)) $((elapsed % 60))
    else
        printf 'FAILED    %s  (exit code %s)\n' "${cfg}" "${status}"
        if [ "${stop_on_error}" = yes ]; then
            echo
            echo "--stop-on-error was given, so the remaining $((total - index)) run(s) were not started."
            break
        fi
        echo "Carrying on with the next dataset."
    fi
    echo
done

# -------------------------------------------------------------------------------------------------
# STAGE 3: the summary. On a queue left running overnight this is the part that is read.
# -------------------------------------------------------------------------------------------------
queue_elapsed=$(($(date +%s) - queue_started))
failures=0

echo "==================================================================================="
echo "SUMMARY"
echo "==================================================================================="
index=0
for cfg in "${cfg_files[@]}"; do
    if [ "${index}" -ge "${#statuses[@]}" ]; then
        printf '    %-12s %s\n' "not started" "${cfg}"
    else
        elapsed="${durations[${index}]}"
        if [ "${statuses[${index}]}" -eq 0 ]; then
            printf '    %-12s %s  (%dh %02dm %02ds)\n' "ok" "${cfg}" \
                   $((elapsed / 3600)) $(((elapsed % 3600) / 60)) $((elapsed % 60))
        else
            printf '    %-12s %s  (exit code %s)\n' "FAILED" "${cfg}" "${statuses[${index}]}"
            failures=$((failures + 1))
        fi
    fi
    index=$((index + 1))
done
echo
printf '    %d of %d run(s) succeeded, total time %dh %02dm %02ds\n' \
       $((${#statuses[@]} - failures)) "${total}" \
       $((queue_elapsed / 3600)) $(((queue_elapsed % 3600) / 60)) $((queue_elapsed % 60))
echo "==================================================================================="
echo

exit "${failures}"
